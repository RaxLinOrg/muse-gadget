"""Bake the radar page's place table, coastlines included.

The coastline comes from Natural Earth's 50m coastline GeoJSON:

    curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_coastline.geojson
    tools/muse/make_places.py ne_50m_coastline.geojson components/muse_radar/muse_radar_places.h

Points are stored as milli-degrees from the place's centre: 0.06 nm a step,
under a pixel even on the 12 NM range, and comfortably inside int16. Each
polyline ends with a MUSE_RADAR_BREAK sentinel.
"""
import json
import math
import sys

# Clipped to this, since it is the widest range the page offers.
RANGE_NM = 250.0
BREAK = -32768

PLACES = [
    ("Bay Area",      37.7749, -122.4194),
    ("Los Angeles",   33.9425, -118.4081),
    ("New York",      40.6413,  -73.7781),
    ("Texas",         32.8998,  -97.0403),
    ("Hormuz",        26.5667,   56.2500),
    ("Taiwan Strait", 24.5000,  119.5000),
    ("Japan",         35.5533,  139.7811),
    ("Korea",         37.4602,  126.4407),
    ("Malacca",        2.5000,  101.0000),
    ("Panama",         9.0800,  -79.6800),
]


def clip(features, lat0, lon0):
    """Coastline inside the box, as runs of (dlat, dlon) in milli-degrees."""
    dlat = RANGE_NM / 60.0
    dlon = dlat / math.cos(math.radians(lat0))
    runs = []
    for feat in features:
        geom = feat["geometry"]
        lines = ([geom["coordinates"]] if geom["type"] == "LineString"
                 else geom["coordinates"])
        for line in lines:
            cur = []
            for lon, lat in line:
                if abs(lat - lat0) <= dlat * 1.1 and abs(lon - lon0) <= dlon * 1.1:
                    cur.append((round((lat - lat0) * 1000.0),
                                round((lon - lon0) * 1000.0)))
                else:
                    if len(cur) > 1:
                        runs.append(cur)
                    cur = []
            if len(cur) > 1:
                runs.append(cur)
    return runs


